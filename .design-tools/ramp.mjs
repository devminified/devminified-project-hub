function emit(name, map, hue) {
  console.log(`\n--- ${name} (h=${hue}) ---`);
  for (const [k, [L, C]] of Object.entries(map)) {
    const cap = maxChroma(L, hue);
    const cc = Math.min(C, cap);
    const hex = oklchToHex(L, cc, hue);
    const flag = C > cap + 0.0005 ? `  !! clipped from ${C} to ${cap.toFixed(3)}` : "";
    console.log(
      `${name}-${k}`.padEnd(14),
      `oklch(${L.toFixed(3)} ${cc.toFixed(3)} ${hue})`.padEnd(28),
      hex,
      ` vs#fff ${contrast(hex, "#ffffff").toFixed(2)}`,
      ` vs#000 ${contrast(hex, "#000000").toFixed(2)}`,
      flag
    );
  }
}
emit("brand", brand, BH);
emit("neutral", neutral, NH);
